import 'dart:convert';
import 'dart:io';

import 'package:sketch_rush/app/domain/questions/question_engine.dart';

/// Generates the committed, server-side question bank migration.
///
/// Run from the repository root:
///   dart run tool/generate_question_bank.dart
///
/// The bank is deterministic. Regenerating produces the same content (IDs are
/// assigned by the database) so diffs stay reviewable.
void main() {
  const perCombination = 8;
  final questions =
      QuestionEngine.generateBatch(count: perCombination, seedOffset: 77000);

  if (questions.length < 1000) {
    stderr.writeln('Expected at least 1000 questions, got ${questions.length}');
    exitCode = 1;
    return;
  }

  final buffer = StringBuffer()
    ..writeln('-- ============================================================================')
    ..writeln('-- Migration 020: MathClash question bank (generated)')
    ..writeln('--')
    ..writeln('-- Generated by: dart run tool/generate_question_bank.dart')
    ..writeln('-- Engine version: ${QuestionEngine.bankVersion}')
    ..writeln('-- Questions: ${questions.length}')
    ..writeln('--')
    ..writeln('-- Do not edit by hand. Update the engine and regenerate.')
    ..writeln('-- ============================================================================')
    ..writeln();

  const columns = '(grade, topic, difficulty, skill, question_text, '
      'answer_type, correct_answer, options, explanation, hint, visual, '
      'estimated_seconds, curriculum_tags, source)';

  for (var start = 0; start < questions.length; start += 100) {
    final end = (start + 100).clamp(0, questions.length);
    buffer.writeln('INSERT INTO math_questions $columns VALUES');
    for (var index = start; index < end; index++) {
      final question = questions[index];
      final visual = question.visual == null
          ? 'NULL'
          : "'${_escapeJson(jsonEncode(question.visual!.toJson()))}'::jsonb";
      final options =
          question.options.map((option) => "'${_escape(option)}'").join(', ');
      final tags = question.curriculumTags
          .map((tag) => "'${_escape(tag)}'")
          .join(', ');
      buffer.write(
        '(${question.grade}, '
        "'${question.topic.dbValue}', "
        "'${question.difficulty.dbValue}', "
        "'${_escape(question.skill)}', "
        "'${_escape(question.text)}', "
        "'${question.answerType.dbValue}', "
        "'${_escape(question.correctAnswer)}', "
        "ARRAY[$options]::text[], "
        "'${_escape(question.explanation)}', "
        "'${_escape(question.hint ?? '')}', "
        '$visual, '
        '${question.estimatedSeconds}, '
        "ARRAY[$tags]::text[], "
        "'${_escape(question.source)}')",
      );
      buffer.writeln(index == end - 1 ? ';' : ',');
    }
    buffer.writeln();
  }

  buffer
    ..writeln('-- Keep the bank searchable and deduplicated.')
    ..writeln('CREATE UNIQUE INDEX IF NOT EXISTS idx_math_questions_unique')
    ..writeln('  ON math_questions (grade, topic, difficulty, question_text, correct_answer);')
    ..writeln()
    ..writeln('ANALYZE math_questions;');

  final file = File('supabase/migrations/020_seed_math_questions.sql');
  file.writeAsStringSync(buffer.toString());
  stdout.writeln(
    'Wrote ${questions.length} questions to ${file.path} '
    '(${(file.lengthSync() / 1024).round()} KB)',
  );
}

String _escape(String value) => value
    .replaceAll('\\', '\\\\')
    .replaceAll("'", "''")
    .replaceAll('\r', ' ')
    .replaceAll('\n', ' ');

String _escapeJson(String value) => value.replaceAll("'", "''");
